// Writes each icon's SVG data from @iconify-json/fluent into the icon item's set file, so the
// Icon component never loads from the Iconify API. `--check` fails instead when the file is stale.
// Add an icon: add `name: { id: 'fluent:<icon>' }` to the set file, then run `pnpm icons`.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

interface IconifyJson {
  prefix: string
  width?: number
  height?: number
  icons: Record<string, { body: string; width?: number; height?: number }>
  aliases?: Record<string, { parent: string; [transform: string]: unknown }>
}

const setFile = fileURLToPath(new URL('../registry/lib/icon/sets/fluent.ts', import.meta.url))
const json = createRequire(import.meta.url)('@iconify-json/fluent/icons.json') as IconifyJson
const { fluent } = (await import(setFile)) as { fluent: Record<string, { id: string }> }

function iconData(id: string) {
  const [prefix, name, ...rest] = id.split(':')
  if (prefix !== json.prefix || !name || rest.length)
    throw new Error(`${id}: not a ${json.prefix}: id`)
  let icon = json.icons[name]
  for (let key = name, hops = 0; !icon; hops++) {
    const alias = json.aliases?.[key]
    if (!alias || hops > 8) throw new Error(`${id}: no such icon in @iconify-json/${json.prefix}`)
    // A transform (rotate, flip) would need Iconify's own resolver; none of ours uses one.
    if (Object.keys(alias).some((k) => k !== 'parent'))
      throw new Error(`${id}: alias with a transform`)
    key = alias.parent
    icon = json.icons[key]
  }
  return {
    id,
    width: icon.width ?? json.width ?? 16,
    height: icon.height ?? json.height ?? 16,
    body: icon.body,
  }
}

const entries = Object.entries(fluent).map(
  ([name, { id }]) => `  ${JSON.stringify(name)}: ${JSON.stringify(iconData(id))},`,
)
const source = `// Generated by \`pnpm icons\` from @iconify-json/fluent. Edit only the names and ids.

/** Internal icon names to Fluent icons, with their SVG data so nothing loads at runtime. */
export const fluent = {
${entries.join('\n')}
} as const

export type IconName = keyof typeof fluent
`
const output = await format(source, { ...(await resolveConfig(setFile)), filepath: setFile })

if (process.argv.includes('--check')) {
  if (readFileSync(setFile, 'utf8') !== output) {
    console.error('registry/lib/icon/sets/fluent.ts is stale: run `pnpm icons`.')
    process.exit(1)
  }
} else {
  writeFileSync(setFile, output)
}
